print("SCENARIO: 500 CONCURRENT USERS")
print("=" * 65)
print()

scenarios = [
    ("Optimistic (similar queries)", 0.75, 0.85),
    ("Realistic (mixed queries)", 0.50, 0.70),
    ("Pessimistic (diverse queries)", 0.25, 0.50),
]

for name, answer_hit_rate, tool_hit_rate in scenarios:
    print("--- {} ---".format(name))
    print("  Answer cache hit rate: {:.0f}%".format(answer_hit_rate * 100))
    print("  Tool data cache hit rate: {:.0f}%".format(tool_hit_rate * 100))
    print()

    cache_hits = int(500 * answer_hit_rate)
    cache_misses = 500 - cache_hits

    print("  Cache HITS: {} requests".format(cache_hits))
    print("    - Redis GET only: ~1ms each")
    print("    - DB pool needed: 0")
    print("    - LLM calls needed: 0")
    print("    - Total time: ~{:.1f}s (parallel)".format(cache_hits * 1 / 1000))
    print()

    tool_queries = int(cache_misses * (1 - tool_hit_rate))
    print("  Cache MISSES: {} requests".format(cache_misses))
    print("    - Tool data from cache: {}".format(cache_misses - tool_queries))
    print("    - Tool data from DB: {}".format(tool_queries))
    print("    - DB queries needed: ~{} (+ {} for session)".format(tool_queries, cache_misses))
    print("    - LLM calls needed: {}".format(cache_misses))
    print()

    total_db = tool_queries + cache_misses
    batches = (total_db + 29) // 30
    queue_time = batches * 3

    print("  DB POOL USAGE:")
    print("    - Total queries: {}".format(total_db))
    print("    - With 30 connections: {} batches".format(batches))
    print("    - Queue wait: ~{}ms".format(queue_time))
    print("    - Pool utilization: {:.1f}%".format(total_db / 30))
    print()

    print("  REAL BOTTLENECK: LLM API")
    print("    - {} LLM calls needed".format(cache_misses))
    print("    - DeepInfra free tier: ~10-20 RPM")
    print("    - DeepInfra paid tier: ~100-1000 RPM")
    print("    - Time to process: {:.0f}s (free) or {:.1f}s (paid)".format(
        cache_misses / 15 * 60, cache_misses / 500 * 60))
    print()

